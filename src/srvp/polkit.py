"""Polkit rule generator for passwordless systemctl unit management."""

from __future__ import annotations

import json

from srvp.config import ProfilesFile


def generate_polkit_rules(config: ProfilesFile, group: str | None = None) -> str:
    """Generate a Polkit .rules snippet allowing passwordless systemctl management for profile units.

    If `group` is None, both 'sudo' (Debian/Ubuntu) and 'wheel' (Fedora/RHEL/Arch/openSUSE)
    admin groups are permitted so the rule works across major Linux distributions.
    """
    managed_units: set[str] = set()
    for profile in config.profiles.values():
        managed_units.update(profile.effective_system_units())
        managed_units.update(profile.effective_ensure_stopped_units())

    sorted_units = sorted(managed_units)
    units_js_array = ",\n        ".join(json.dumps(u) for u in sorted_units)

    if group:
        group_comment = "configured admin group"
        group_expr = f"subject.isInGroup({json.dumps(group)})"
    else:
        group_comment = "'sudo' or 'wheel' admin groups"
        group_expr = '(subject.isInGroup("sudo") || subject.isInGroup("wheel"))'

    return f"""// Generated by Linux Service Profiles (srvp)
// Save this file to: /etc/polkit-1/rules.d/50-srvp-systemd.rules
// Allows members of the {group_comment} to start/stop/restart configured profile units without a password.

polkit.addRule(function(action, subject) {{
    var allowedUnits = [
        {units_js_array}
    ];

    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        {group_expr} &&
        allowedUnits.indexOf(action.lookup("unit")) !== -1) {{
        return polkit.Result.YES;
    }}
}});
"""
